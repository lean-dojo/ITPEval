def reading_section(prover, title, profile):
    reading = profile["reading"]
    source = LIBRARY / prover / reading.get("file", "library/" + ENTRY[prover])
    first, last = reading.get("lines", profile["example_lines"])
    excerpt = "\n".join(source.read_text(encoding="utf-8").splitlines()[first - 1:last])
    comment = reading.get("comment", profile["example_comment"])
    proof = reading.get("fragment")
    if excerpt.count(proof or profile["example_symbol"]) != 1:
        raise ValueError(f"Review the proof excerpt for {prover}")
    attribute = f' data-proof="{escape(proof, quote=True)}"' if proof else ""
    source_url = "../../" + source.relative_to(ROOT.parent).as_posix()
    explanation = profile["explanation"]
    return [
        "## Read a proof", "", reading["definition"], "",
        f'<figure class="proof-listing" data-listing="{prover}"{attribute} markdown="1">', "",
        f'<figcaption markdown="span"><strong>{title}</strong> [{source.name}]({source_url})</figcaption>', "",
        f"```{prover}", comment, excerpt, "```", "", "</figure>", "",
        "**The claim.** " + reading["claim"], "", "**The proof.** " + reading["proof"], "",
        reading["why"], "",
        '<details markdown="1">', f'<summary>{escape(explanation["question"])}</summary>', "",
        explanation["answer"], "", "</details>", "",
    ]


def theory_section(profile):
    explanation = profile["explanation"]
    label, reference = explanation["theory_reference"]
    first, second = explanation["foundations"]
    return ["## How proof checking works", "", first, "", f"{second} [{label}]({reference})", ""]


