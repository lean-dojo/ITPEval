def interaction_records(directory):
    def records(source, result, operations):
        return ({"prover": result["prover"], "prover_build": result["prover_build"],
                 "environment_id": result["environment_id"], "operation": operation,
                 "status": "implemented/tested", "evidence_path": source}
                for operation in operations)

    checkpoints = directory / "document-checkpoints.jsonl"
    if checkpoints.is_file():
        for line in checkpoints.read_text().splitlines():
            result = json.loads(line)
            if (result["original"] == result["restored"] == "accepted"
                    and result["fork"] in {"rejected", "incomplete"}):
                yield from records(checkpoints.name, result, ("fork_document", "checkpoint_document"))
    for source in ("evidence/native-depth.json", "evidence/hol-branches.json", "evidence/lean-horn-search.json",
                   "evidence/rocq-horn-search.json", "pvs-proof-sessions.json", "native-proof-driver.json",
                   "atp-from-session.json", "hol-automation.json", "native-search.json", "proof-portfolios.json"):
        evidence = directory / source
        if evidence.is_file():
            results = json.loads(evidence.read_text(encoding="utf-8"))
            for result in [results] if isinstance(results, dict) else results:
                registered = {cap.operation for cap in get_backend(result["prover"]).capabilities()}
                checks = result["operations"]
                if source == "atp-from-session.json" and {arm["solver"]["solver"] for arm in result["solvers"]
                                                          if arm["outcome"] == "accepted"} >= {"e", "vampire"}:
                    checks = {**checks, "external_atp_goal": True}
                operations = (key for key, passed in checks.items() if passed is True and key in registered)
                yield from records(source, result, operations)
    pilot = directory / "atp-pilot.json"
    if pilot.is_file():
        result = json.loads(pilot.read_text(encoding="utf-8"))
        checked_solvers = {row["arm"] for row in result["hybrid"] if row["checked"] is True}
        if {"e", "vampire"}.issubset(checked_solvers):
            yield from records(pilot.name, {"prover": "isabelle", **result}, ("automated_search",))
    warm = directory / "hol-light-worker.json"
    if warm.is_file():
        result = json.loads(warm.read_text(encoding="utf-8"))
        for case in ("branching", "imports"):
            native = result["native_results"][case]
            if native["checks"] and all(passed is True for passed in native["checks"].values()):
                yield from records(warm.name, {"prover": "hol-light", **native}, ("warm_proof_session",))


def generate(destination, report, interaction_report=None):
    rows = [json.loads(line) for line in report.read_text().splitlines() if line] if report.is_file() else []
    reports = {(row["prover"], row["operation"]): row for row in rows}
    current_interactions = list(interaction_records(report.parent))
    if interaction_report is not None:
        jsonl(interaction_report, current_interactions)
    tested_operations = {}
    for row in current_interactions:
        tested_operations.setdefault(row["prover"], set()).add(row["operation"])
    common = ["installed_package", "check_artifact", "proof_completion", "fixed_context", "edit_document", "reset",
              "fork_document", "checkpoint_document", "inspect_declarations", "episode_replay", "end_to_end",
              "evaluation_parity"]
    operations = common + ["inspect_goals", "step_proof", "refine_hole", "case_split", "replay_stack",
                           "proof_branching", "checkpoint_proof", "checkpoint_actions", "warm_proof_session",
                           "automated_search", "atp_from_state", "external_atp_goal", "proof_portfolio", "snapshot", "action_traces",
                           "bounded_equivalence"]
    registered = {cap.operation for prover in prover_ids() for cap in get_backend(prover).capabilities()}
    operations.extend(sorted(({row["operation"] for row in rows} | registered) - set(operations)))
    matrix = ["# Backend capabilities", "",
              "All ten built-in provers can check native source, verify a fixed proof task, "
              "extract declarations and replay a sequence of edits. Check the second table before "
              "building an agent that needs individual tactics, goal states or proof branching.", "",
              "**Tested** marks an operation with a passing native example in a recorded environment. **Experimental** marks "
              "an implementation awaiting a passing example in these reports. **Planned** marks an operation "
              "awaiting a public implementation. **N/A** means the operation does not apply."]
    profiles = json.loads((ROOT.parent / "website/provers.json").read_text())
    matrix += ["", "For compatible library layouts and concrete imports, see [Provers and libraries](../provers/index.md)."]
    if any("checkpoint_document" in available for available in tested_operations.values()):
        matrix += ["", "The portable document checkpoint test forks a rejected edit and restores "
                   "the accepted artifact in a fresh session. [Native results](../../benchmarks/runtime/document-checkpoints.jsonl) "
                   "· [Fork and save a document](../runtime/execution/document-revisions.md#fork-and-save-a-document)"]
    if tested_operations:
        matrix += ["", "Native proof feedback can be a tactic goal, an interaction hole, or a thesis "
                   "observed while checking a complete article. [Interfaces and native evidence](../runtime/execution/native-interaction.md#native-interaction)"]
    summary = {}
    field_summary = {}
    titles = {}
    exercises = []
    for prover in prover_ids():
        meta = json.loads((ROOT / "provers" / prover / "adapter.json").read_bytes())
        backend = get_backend(prover)
        caps = {cap.operation: cap.status for cap in backend.capabilities()}
        caps["inspect_declarations"] = "experimental" if prover in ADAPTERS else "planned"
        caps.update(fixed_context="experimental", episode_replay="experimental", end_to_end="experimental",
                    evaluation_parity="experimental", installed_package="experimental")
        caps["bounded_equivalence"] = "experimental" if prover == "lean4" else "inapplicable"
        for operation in tested_operations.get(prover, ()):
            caps[operation] = "implemented/tested"
        extraction = reports.get((prover, "inspect_declarations"))
        fields = {}
        if extraction and extraction.get("status") == "implemented/tested":
            raw = json.loads((report.parent / extraction["evidence_path"]).read_bytes())
            fields = raw.get("fields", raw.get("report", {}).get("fields", {}))
            for op in ("proof_used_premises", "term_trees"):
                availability = fields.get(op)
                if availability == "observed":
                    caps[op] = "implemented/tested"
                elif availability == "inapplicable":
                    caps[op] = "inapplicable"
        data = [reports.get((prover, op), {}) for op in operations]
        status = [entry["status"] if entry.get("status") == "implemented/tested" else caps.get(op, "planned")
                  for op, entry in zip(operations, data)]
        link = f"[{meta['name']}](../provers/{prover}.md)"
        summary[link] = dict(zip(operations, status))
        field_summary[link] = fields
        profile = profiles[prover]
        title = "Isabelle/HOL" if prover == "isabelle" else meta["name"]
        manifest = json.loads((curated_project(prover) / "completion.json").read_text())
        titles[prover] = title
        correct, first = manifest["allowed_edits"][:2]
        exercises.append(f"| [{title}](../provers/{prover}.md#proof-completion) | `{manifest['entrypoint']}` | "
                         f"`{first}` | `{correct}` |")
        notes = ["# " + title, "", f"{profile['description']} "
                 f"[Project documentation]({profile['reference']})", "",
                 *theory_section(profile), *reading_section(prover, title, profile),
                 *project_section(prover, profile), "## Libraries", "", profile["library_core"], "",
                 *[f"- [{lib['name']}]({lib['url']}) — {lib['description']}." for lib in profile["libraries"]],
                 "", profile["library_setup"], "", "### Extract a library", "", profile["library_example"], "",
                 library_workflow(prover, profile), ""]
        if prover == "lean4":
            notes += [LEAN_PROOF_SOURCE, ""]
        if prover == "pvs":
            notes += ["### Check the extracted library lemma", "", PVS_PROOF, ""]
        notes += completion_section(prover, title, profile, manifest)
        notes += ["## See also", ""]
        if prover == "isabelle":
            notes += ["", "[Isa-REPL proof steps and state handles](../runtime/isa-repl.md)"]
        if prover in {"hol4", "hol-light", "pvs"}:
            notes += ["", "[HOL tactic and PVS sequent observations](../runtime/hol-and-pvs-interaction.md)"]
        notes += ["", "[Compare supported operations](../reference/capabilities.md) · " + f"[Native adapter sources and version script](../../itpeval/provers/{prover})"]
        (destination / "provers" / f"{prover}.md").write_text("\n".join(notes) + "\n")
    practice = destination / "start/proof-completion.md"
    begin, end = "<!-- completion-examples -->", "<!-- end-completion-examples -->"
    before, table = practice.read_text(encoding="utf-8").split(begin)
    _, after = table.split(end)
    exercise_table = ["| Prover | File to edit | Starting fragment | One accepted completion |", "|---|---|---|---|", *exercises]
    practice.write_text(before + begin + "\n\n" + "\n".join(exercise_table) + "\n\n" + end + after, encoding="utf-8")

    directory = ["# Provers and libraries", "",
                 "Choose a prover to see how its logic works, read a proof in the native language, and load a project. "
                 "Each guide also has a short proof you can edit yourself. [VS Code exercises](../start/proof-completion.md#choose-your-prover)", "",
                 "| Prover | Worked proof | Logical foundation | Library examples |", "|---|---|---|---|"]
    for key in sorted(profiles, key=lambda k: titles[k].casefold()):
        profile = profiles[key]
        examples = ", ".join(lib["name"] for lib in profile["libraries"])
        directory.append(f"| [{titles[key]}]({key}.md) | [Read the proof]({key}.md#read-a-proof) | "
                         f"[{profile['theory']}]({key}.md#how-proof-checking-works) | [{examples}]({key}.md#libraries) |")
    directory += ["", "## Bring your own files", "",
                  "The examples use small bundled projects so you can read the whole proof. You can also point ITPEval "
                  "at a file you already have. For example, Lean loads compiled dependencies, Rocq maps logical names "
                  "to compiled modules, and Metamath follows the database’s include paths. For a proof-completion "
                  "exercise, choose the theorem and the region a candidate can edit. "
                  "[Check your own files](../guides/work-with-a-library.md)", "",
                  "[Compare proof and extraction features](../reference/capabilities.md) · [Install a prover](../runtime/toolchains.md)"]
    (destination / "provers/index.md").write_text("\n".join(directory) + "\n")

    def table(title, columns, rows):
        matrix.extend(["", "## " + title, "", "| Feature | Availability by prover |", "|---|---|"])
        labels = {"implemented/tested": "Tested", "inapplicable": "N/A"}
        for column in columns:
            groups = {}
            for link, values in rows.items():
                status = values.get(column, "unreported")
                groups.setdefault(labels.get(status, status.capitalize()), []).append(link)
            parts = []
            for label, provers in groups.items():
                names = "all ten provers" if len(provers) == len(rows) else ", ".join(provers)
                parts.append(f"**{label}** · {names}")
            matrix.append(f"| `{column}` | " + "<br>".join(parts) + " |")

    table("Documents, extraction and evaluation", common, summary)
    table("Native interactions and semantic checking", operations[len(common):], summary)
    fields = sorted({field for values in field_summary.values() for field in values})
    if fields:
        table("Extracted structural fields", fields, field_summary)
    matrix.extend(["", "Document reset discards candidate revisions. Ephemeral handles identify a session and worker generation. "
                   "Branching a proof and saving a process snapshot are distinct operations.",
                   "", "[Historical release records](../../benchmarks/runtime/qualification.jsonl) · "
                   "[Stable-toolchain interaction records](../../benchmarks/runtime/interaction-capabilities.jsonl)"])
    (destination / "reference" / "capabilities.md").write_text("\n".join(matrix) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=Path("benchmarks/runtime/qualification.jsonl"))
    parser.add_argument("--interaction-report", type=Path, help="write exact-lock interaction capability records")
    args = parser.parse_args()
    generate(ROOT.parent / "docs", args.report, args.interaction_report)
