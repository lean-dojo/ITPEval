$(
  Addresses are represented exactly by ZZ X. ZZ, with base and offset given
  by 1st and 2nd. NTP4VCShift, NTP4VCValidRW, NTP4VCSint8,
  NTP4VCSint32, NTP4VCUint64, NTP4VCValidStr, and NTP4VCStrneq directly
  expand the corresponding source definitions.

  The arbitrary map F and sets G and H represent region, linked, and sconst.
  I and J represent to_uint64 and to_sint32. K and L represent l_strlen and
  l_strncmp_2'. Their source range, identity, and fixed-point laws are
  retained as explicit hypotheses without assigning stronger properties to
  these symbols.

  The source let-bindings a_2, x, a_3, x_1, and x_2 are expanded at every
  use. All addresses, integers, functions, and predicates retain their
  unrestricted source domains. The null-position witnesses in valid-string
  predicates remain internally existential, and the prefix assumption keeps
  its full integer quantifier and implication scope. Splitting the source
  implication chain into scoped essential hypotheses is bidirectionally
  equivalent to the original statement. The final declaration is Metamath's
  native unproved $a statement encoding; this database contains no $p
  declaration.
$)

