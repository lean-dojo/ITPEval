$(
  Addresses are represented exactly by ZZ X. ZZ, with base and offset given by
  1st and 2nd. NTP4VCShift, NTP4VCSeparated, and NTP4VCValidRW expand the
  corresponding source definitions. NTP4VCHavoc is the source havoc function
  fixed by havoc_access, and NTP4VCUpdate is full-domain functional update.

  NTP4VCLinkedN is equivalent to the source inductive p_linked_n predicate. An
  integer-indexed address function records the finite chain from the root at
  position zero to the bound at position n. At each integer k with 0 <= k < n,
  it records the array entry, the writable-node condition, and the next-pointer
  step. The displayed nonnegative length and index bounds are exactly those
  generated by the inductive base and constructor rules.

  NTP4VCSwipeRight directly expands p_array_swipe_right. In the source
  p_unchanged assumption the allocation maps and real memories on the two
  sides are identical. NTP4VCUnchanged therefore retains exactly the two
  nontrivial, bidirectionally equivalent fields: equality of each array pointer
  and equality of the corresponding next-pointer reads. The float fields and
  writable implication then follow from pointer equality, while the converse
  follows from the first two conjuncts of the source definition.

  The source let-bound integers, addresses, and maps are expanded at every use.
  The unconstrained source region function and linked predicate are represented
  by an arbitrary integer map and an arbitrary subset of integer maps. The
  final declaration is Metamath's native unproved $a statement encoding; this
  database adds no $p proof declaration.
$)

