$[ lib/set.mm $]

$(
  Addresses are represented exactly by ZZ X. ZZ, with base and offset given by
  1st and 2nd. NTP4VCShift, NTP4VCSeparated, NTP4VCValidRW, NTP4VCSint32,
  and NTP4VCFramed expand the corresponding source definitions. The arbitrary
  integer-valued map H represents the source region function, and membership
  of the allocation map E in the arbitrary set L represents the source linked
  predicate.

  NTP4VCLinkedN is equivalent to the source inductive p_linked_n predicate. An
  integer-indexed address function records the finite chain from the root at
  position zero to the bound at position n. At each integer k with 0 <= k < n,
  it records the array entry, the writable-node condition, and the next-pointer
  step. The displayed nonnegative length and index bounds are exactly those
  generated by the inductive base and constructor rules.

  NTP4VCUpdate is functional update on the full address domain. The source
  let-bound values a_3 = shift a_2 0, a_4 = t_1 a, and
  m = update t_1 a_1 a_4 are expanded at every use. The interval separation
  hypothesis retains its universal quantifier over all integers. The final
  declaration is Metamath's native unproved $a statement encoding; this
  database adds no $p proof declaration.
$)

