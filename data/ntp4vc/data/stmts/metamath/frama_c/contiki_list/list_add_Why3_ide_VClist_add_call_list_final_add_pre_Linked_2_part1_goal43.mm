$(
  Addresses are represented exactly by ZZ X. ZZ, with base and offset given by
  1st and 2nd. NTP4VCShift, NTP4VCSeparated, NTP4VCValidRW,
  NTP4VCSint32, and NTP4VCFramed expand the corresponding source definitions.
  NTP4VCHavoc is the source havoc function fixed pointwise by havoc_access,
  NTP4VCUpdate is full-domain functional update, and NTP4VCMid expands the
  source let-bound map m.

  NTP4VCLinkedN is equivalent to the source inductive p_linked_n predicate. An
  integer-indexed address function records the finite chain from the root at
  position zero to the bound at position n. At each integer k with 0 <= k < n,
  it records the array entry, the writable-node condition, and the next-pointer
  step. The displayed nonnegative length and index bounds are exactly those
  generated by the inductive base and constructor rules.

  NTP4VCIndexOfEq is the graph of the source l_index_of operation: when the
  upper bound is at most the lower bound its result is the upper-bound
  sentinel; otherwise it is the least matching integer position in the
  half-open interval, or the upper-bound sentinel if there is no match. Under
  the explicit nonnegative lower-bound hypothesis this is bidirectionally
  equivalent to the source index axioms.

  In the source p_unchanged assumption the allocation maps and real memories
  on the two sides are identical. NTP4VCUnchanged therefore retains exactly
  the two nontrivial, bidirectionally equivalent fields: equality of each
  array pointer and equality of the corresponding next-pointer reads. The
  float fields and writable implication follow from pointer equality, while
  the converse follows from the first two conjuncts of the source definition.
  Likewise, the eqs1_list hypothesis at a_3 reduces exactly to equality of its
  next-pointer fields because all three real fields use the same real memory.

  The remaining source let-bound integers, addresses, and maps are expanded at
  every use. The arbitrary source region function and linked predicate are
  represented by an arbitrary integer map and an arbitrary subset of integer
  maps. The final declaration is Metamath's native unproved $a statement
  encoding; this database adds no $p proof declaration.
$)

