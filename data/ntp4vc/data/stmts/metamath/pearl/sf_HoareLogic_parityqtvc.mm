$(
  Statement-only formalization of the NTP4VC corpus artifact
  pearl/sf_HoareLogic_parityqtvc: the parity Hoare-logic verification
  condition states initialization and universally quantified loop-step
  obligations for a nonnegative integer input. This file contains no proof.
$)

$[ lib/set.mm $]

$(
  SetMM's ZZ is the full unbounded integer domain. A is the source input x,
  while y and z are the source loop variables y and x1 and remain internally
  universally quantified over all integers.

  E is exactly the source inductive predicate even: it is a subset of ZZ
  containing zero, closed under addition by two, and has no proper subset
  with those same constructor-closure properties. Thus E is the least subset
  generated by even_0 and even_odd, not an arbitrary closed predicate.

  The proposition-valued source conditional on z being nonzero is expanded
  into two exhaustive guarded branches. This is bidirectionally equivalent
  to the source if-then-else. The conjunction nesting, arithmetic
  expressions, assumption, conclusion, and quantifier scopes are preserved
  without simplifying any verification obligation. The final declaration is
  Metamath's native unproved $a statement encoding; this database contains no
  artifact-level $p proof declaration.
$)

${
  $d n q y z A E $.

  $( Exact least fixed-point presentation of the source predicate even. $)
  ntp4vc-parity-even-subset
    $e |- E C_ ZZ $.

  ntp4vc-parity-even-zero
    $e |- 0 e. E $.

  ntp4vc-parity-even-add-two
    $e |- A. n e. ZZ
      (
        n e. E
        ->
        ( n + 2 ) e. E
      ) $.

  ntp4vc-parity-even-structural-induction
    $e |- A. q e. ~P E
      (
        (
          0 e. q
          /\
          A. n e. ZZ
            (
              n e. q
              ->
              ( n + 2 ) e. q
            )
        )
        ->
        q = E
      ) $.

  $( Source theorem parameter A=x and its precondition fact0. $)
  ntp4vc-parity-x-integer
    $e |- A e. ZZ $.

  ntp4vc-parity-x-nonnegative
    $e |- 0 <_ A $.

  ntp4vc-pearl-sf-hoarelogic-parity-vc $a |- (
    0 <_ A
    /\
    (
      (
        ( A - A ) e. E
        \/
        (
          0 = 1
          /\
          ( ( A - A ) + 1 ) e. E
        )
      )
      /\
      A. y e. ZZ A. z e. ZZ
        (
          (
            0 <_ z
            /\
            (
              (
                y = 0
                /\
                ( A - z ) e. E
              )
              \/
              (
                y = 1
                /\
                ( ( A - z ) + 1 ) e. E
              )
            )
          )
          ->
          (
            (
              z =/= 0
              /\
              (
                (
                  0 <_ z
                  /\
                  ( z - 1 ) < z
                )
                /\
                (
                  0 <_ ( z - 1 )
                  /\
                  (
                    (
                      ( 1 - y ) = 0
                      /\
                      ( A - ( z - 1 ) ) e. E
                    )
                    \/
                    (
                      ( 1 - y ) = 1
                      /\
                      ( ( A - ( z - 1 ) ) + 1 ) e. E
                    )
                  )
                )
              )
            )
            \/
            (
              -. z =/= 0
              /\
              ( y = 0 <-> A e. E )
            )
          )
        )
    )
  ) $.
$}
