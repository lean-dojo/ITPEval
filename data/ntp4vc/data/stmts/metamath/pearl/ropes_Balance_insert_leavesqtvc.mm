  Statement-only formalization of the NTP4VC corpus artifact
  pearl/ropes_Balance_insert_leavesqtvc: the verification condition for
  recursively inserting the leaves of a valid rope into a rope queue while
  preserving queue invariants and concatenated-string semantics. This file
  contains no proof.
