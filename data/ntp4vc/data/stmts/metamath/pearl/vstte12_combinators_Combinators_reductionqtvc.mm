${
  $d h x y z A B C D $.

  $(
    Least reflexive relation on B closed under appending an A-step.
    This is the source inductive reflexive-transitive closure relTR.
  $)
  ntp4vc-rtc-definition $a |- (
    ( NTP4VCRTC A B C D )
    <->
    A. h e. ~P ( B X. B )
      (
        (
          A. x e. B
            <. x , x >. e. h
          /\
          A. x e. B A. y e. B A. z e. B
            (
              (
                <. x , y >. e. h
                /\
                <. y , z >. e. A
              )
              ->
              <. x , z >. e. h
            )
        )
        ->
        <. C , D >. e. h
      )
  ) $.
