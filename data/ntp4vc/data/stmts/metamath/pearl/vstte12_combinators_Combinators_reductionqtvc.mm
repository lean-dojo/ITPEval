$(
  Statement-only formalization of the NTP4VC corpus artifact
  pearl/vstte12_combinators_Combinators_reductionqtvc: the VSTTE 2012
  call-by-value S-K combinator verification condition for recursive reduction
  inside a valid evaluation context. This file contains no proof.
$)

$[ lib/set.mm $]

$(
  T and C are exactly the source inductive carriers of finite combinator terms
  and evaluation contexts. Their tagged constructors are injective and
  disjoint within each carrier; closure, exhaustiveness, and structural
  induction exclude missing constructor trees, extraneous values, and
  non-well-founded constructor objects.

  V and I are respectively the source predicates is_value and is_context,
  characterized by their complete constructor equations. F and G are the
  complete recursive functions subst and subst_c. R is exactly the one-step
  call-by-value K/S reduction relation. NTP4VCRTC is its least reflexive
  relation closed under appending one R-step, which is definitionally
  equivalent to the source relTR inductive relation.

  NTP4VCComposeSpec, NTP4VCReductionPost, and NTP4VCValueMatch are faithful
  abbreviations for the generated subst_c postcondition, recursive reduction
  postcondition, and final match on the first reduced value. The final
  assertion keeps the source parameters t and c and hypothesis is_context c
  explicit. Source pattern matches are expanded into disjoint constructor
  cases, while recursive-call results retain their original internal universal
  quantifier scopes. The final $a declaration is Metamath's native unproved
  statement encoding; this database contains no $p proof declaration.
$)

