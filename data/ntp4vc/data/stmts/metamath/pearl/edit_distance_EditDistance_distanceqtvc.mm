${
  $d a i q u v n C D S A B $.

  $( The arbitrary inhabited source character type. $)
  ntp4vc-char-carrier-set $e |- C e. _V $.
  ntp4vc-char-carrier-nonempty $e |- C =/= (/) $.

  $( Exact least relation generated by dist_eps, dist_add_left,
     dist_add_right, and dist_context. $)
  ntp4vc-dist-type $e |- D C_
    ( ( Word C X. Word C ) X. ZZ ) $.
  ntp4vc-dist-closed $e |- ( NTP4VCDistClosed D C ) $.
  ntp4vc-dist-least $e |- A. q e.
    ~P ( ( Word C X. Word C ) X. ZZ )
    (
      ( NTP4VCDistClosed q C )
      ->
      D C_ q
    ) $.

  $( The source suffix operation and its two axioms. $)
  ntp4vc-suffix-function $e |- S e.
    ( ( Word C ) ^m ( Word C X. ZZ ) ) $.
  ntp4vc-suffix-nil $e |- A. u e. Word C
    ( NTP4VCSuffix S u ( # ` u ) ) = (/) $.
  ntp4vc-suffix-cons $e |- A. i e. ZZ A. u e. Word C
    (
      (
        0 <_ i
        /\
        i < ( # ` u )
      )
      ->
      (
        ( NTP4VCSuffix S u i )
        =
        (
          <" ( u ` ( NTP4VCToNat i ) ) ">
          ++
          ( NTP4VCSuffix S u ( i + 1 ) )
        )
      )
    ) $.

  $( Source theorem parameters w1 and w2. $)
  ntp4vc-w1-word $e |- A e. Word C $.
  ntp4vc-w2-word $e |- B e. Word C $.

  ntp4vc-pearl-edit-distance-distance-vc $a |- (
    NTP4VCDistanceVC D S A B
  ) $.
$}
