$(
  Statement-only formalization of the NTP4VC corpus artifact
  pearl/edit_distance_EditDistance_distanceqtvc: the edit-distance dynamic
  programming verification condition initializes a distance row, preserves
  its outer and inner loop invariants through list updates, and returns a
  minimum insertion/deletion distance between two words. This file contains
  no proof.
$)

$[ lib/set.mm $]

$(
  C is the arbitrary nonempty character carrier, Word C is the full type of
  finite character lists, and Word ZZ is the full type of finite integer
  lists. D is characterized below as exactly the least ternary relation
  generated by the four source constructors for dist. S is the source suffix
  function, with both source axioms retained.

  NTP4VCToNat, NTP4VCAt, and NTP4VCSet are the source integer-to-natural
  conversion, totalized integer-list lookup, and list update. The named
  predicates after them only factor the original nested verification
  condition. Expanding their biconditional definitions recovers every source
  quantifier, repeated bound, implication, update-law premise, conditional
  branch, loop invariant, and final minimum-distance conclusion. The source
  proposition-valued conditional is represented by its equivalent pair of
  guarded implications.

  The final $a declaration is Metamath's native unproved statement encoding.
  Every other $a declaration is syntax, a faithful definition, or a source
  suffix axiom; this database contains no $p proof declaration.
$)

