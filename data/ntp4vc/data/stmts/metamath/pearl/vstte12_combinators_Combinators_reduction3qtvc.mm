${
  $d k x A B C D E F G H $.

  $( Integer parity, equivalent to Why3 number.Parity. $)
  ntp4vc-even-definition $a |- (
    ( NTP4VCEven A )
    <->
    E. k e. ZZ A = ( 2 x. k )
  ) $.

  ntp4vc-odd-definition $a |- (
    ( NTP4VCOdd A )
    <->
    E. k e. ZZ A = ( ( 2 x. k ) + 1 )
  ) $.

  $( The postcondition implication generated by a subst_c call. $)
  ntp4vc-compose-spec-definition $a |- (
    ( NTP4VCComposeSpec A B C D )
    <->
    (
      (
        C e. A
        /\
        D e. A
      )
      ->
      ( B ` <. C , D >. ) e. A
    )
  ) $.

  $(
    The complete reduction3 recursive-call postcondition. Here A is the
    one-step relation, B the term carrier, C the value predicate, D subst,
    E the context, F the input term, G the result, and H the integer index.
  $)
  ntp4vc-rec-post-definition $a |- (
    ( NTP4VCRecPost A B C D E F G H )
    <->
    (
      (
        (
          NTP4VCRTC
            A
            B
            ( D ` <. E , F >. )
            ( D ` <. E , G >. )
        )
        /\
        G e. C
      )
      /\
      (
        (
          ( NTP4VCEven H )
          ->
          G = NTP4VCK
        )
        /\
        (
          ( NTP4VCOdd H )
          ->
          G = ( NTP4VCApp NTP4VCK NTP4VCK )
        )
      )
    )
  ) $.

  $( The successful source match branches K and App K v3. $)
  ntp4vc-k-or-app-k-definition $a |- (
    ( NTP4VCKOrAppK A B )
    <->
    (
      A = NTP4VCK
      \/
      E. x e. B
        A = ( NTP4VCApp NTP4VCK x )
    )
  ) $.

  $( The result selected by the final match on the first recursive value. $)
  ntp4vc-result-match-definition $a |- (
    ( NTP4VCResultMatch A B C D )
    <->
    (
      (
        B = NTP4VCK
        /\
        D = ( NTP4VCApp B C )
      )
      \/
      E. x e. A
        (
          B = ( NTP4VCApp NTP4VCK x )
          /\
          D = x
        )
    )
  ) $.
$}

