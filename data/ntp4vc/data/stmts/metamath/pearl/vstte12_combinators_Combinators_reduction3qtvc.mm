$(
  Statement-only formalization of the NTP4VC corpus artifact
  pearl/vstte12_combinators_Combinators_reduction3qtvc: the VSTTE 2012
  call-by-value S-K combinator verification condition for the recursively
  defined all-K term sequence ks, including evaluation contexts,
  reflexive-transitive reduction, and parity-sensitive results. This file
  contains no proof.
$)

$[ lib/set.mm $]

$(
  T and C are exactly the source inductive carriers of finite combinator terms
  and evaluation contexts. Their tagged constructors are injective and
  disjoint within each carrier; closure, exhaustiveness, and structural
  induction exclude missing constructor trees, extraneous values, and
  non-well-founded constructor objects.

  V, I, and O are respectively the source predicates is_value, is_context,
  and only_K, characterized by their complete constructor equations. F and G
  are the complete recursive functions subst and subst_c. R is exactly the
  one-step call-by-value K/S reduction relation. NTP4VCRTC is its least
  reflexive relation closed under appending one R-step, which is
  definitionally equivalent to the source relTR inductive relation. H is the
  source integer-indexed function ks, with its nonnegative recursive equation
  and only_K postcondition.

  NTP4VCEven and NTP4VCOdd are the usual integer parity predicates.
  NTP4VCComposeSpec, NTP4VCRecPost, NTP4VCKOrAppK, and
  NTP4VCResultMatch are faithful abbreviations for the generated function-call
  postconditions and constructor matches in the VC. The final assertion keeps
  n and c universally parameterized through explicit typing hypotheses, keeps
  fact0 and fact1 explicit, and preserves every internal universal and
  existential scope from the two recursive calls. The final $a declaration is
  Metamath's native unproved statement encoding; this database contains no $p
  proof declaration.
$)

