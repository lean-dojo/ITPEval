$(
  Statement-only formalization of PutnamBench corpus artifact
  putnam_2016_a5: bounded signed alternating-word representations in a
  finite group irredundantly generated by two elements, one of odd order.
  This file contains no proof.
$)

$[ lib/set.mm $]

$(
  In SetMM, G e. Grp supplies an arbitrary group, Base ` G is its carrier,
  Fin and # express finiteness and finite cardinality, +g ` G is the group
  operation, invg ` G is inversion, and ( od ` G ) ` g is the order of g.
  The Moore closure in SubGrp ` G is subgroup generation, so the three
  closure conditions state that g and h generate G together while neither
  g nor h generates G alone.

  Word S is the class of all finite sequences with entries in S, # ` w is
  the sequence length, and deleting the empty word gives the lower bound
  one. The internally existential word w therefore has length between one
  and the group cardinality. Its left-to-right group product G gsum w is
  exactly a product of factors g^(+/-1) h^(+/-1). The final declaration is
  the single unproved $a corpus statement; this database contains no $p
  proof declaration.
$)

${
  $d G S g h w x $.

  putnambench-putnam-2016-a5 $a |-
    A. G
      A. g e. ( Base ` G ) A. h e. ( Base ` G ) A. S
        (
          (
            (
              (
                G e. Grp
                /\
                ( Base ` G ) e. Fin
              )
              /\
              (
                (
                  (
                    ( ( mrCls ` ( SubGrp ` G ) ) ` { g , h } )
                    =
                    ( Base ` G )
                  )
                  /\
                  (
                    ( ( mrCls ` ( SubGrp ` G ) ) ` { g } )
                    =/=
                    ( Base ` G )
                  )
                )
                /\
                (
                  ( ( mrCls ` ( SubGrp ` G ) ) ` { h } )
                  =/=
                  ( Base ` G )
                )
              )
            )
            /\
            ( ( od ` G ) ` g ) e. Odd
          )
          /\
          S =
            (
              {
                ( g ( +g ` G ) h ) ,
                ( ( ( invg ` G ) ` g ) ( +g ` G ) h )
              }
              u.
              {
                ( g ( +g ` G ) ( ( invg ` G ) ` h ) ) ,
                (
                  ( ( invg ` G ) ` g )
                  ( +g ` G )
                  ( ( invg ` G ) ` h )
                )
              }
            )
          ->
          A. x e. ( Base ` G )
            E. w e. ( Word S \ { (/) } )
              (
                ( # ` w ) <_ ( # ` ( Base ` G ) )
                /\
                ( G gsum w ) = x
              )
        )
  $.
$}
