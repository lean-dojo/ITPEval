$(
  Statement-only formalization of PutnamBench corpus artifact
  putnam_2002_a6: the bases for which the reciprocal series generated by
  the base-digit-length recurrence converges are exactly the singleton
  containing base 2. This file contains no proof.
$)

$[ lib/set.mm $]

$(
  The function f is an arbitrary real-valued family indexed by a base and a
  nonnegative integer. For every base b at least 2, its initial values are 1
  and 2. For n at least 3, the internally existential positive integer d is
  characterized by

    b^(d-1) <= n < b^d,

  which for b >= 2 uniquely says that d is the number of base-b digits of n.
  The recurrence then has exactly the source form f(b,n) = n f(b,d).

  For m in NN0, 1 ... m is the inclusive finite interval, empty when m is
  zero, so the mapped finite sum is the source sequence of real partial sums.
  Its real limit L remains existentially quantified inside the set-builder.
  Equality with { 2 } inlines the solution value recorded by the sources.

  The final declaration is the single unproved $a corpus statement; this
  database contains no $p proof statement.
$)

${
  $d b d f L m n $.

  putnambench-putnam-2002-a6 $a
    |- A. f e. ( RR ^m ( NN0 X. NN0 ) )
      (
        (
          A. b e. NN
            (
              2 <_ b
              ->
              (
                (
                  ( f ` <. b , 1 >. ) = 1
                  /\
                  ( f ` <. b , 2 >. ) = 2
                )
                /\
                A. n e. NN
                  (
                    3 <_ n
                    ->
                    E. d e. NN
                      (
                        (
                          ( b ^ ( d - 1 ) ) <_ n
                          /\
                          n < ( b ^ d )
                        )
                        /\
                        ( f ` <. b , n >. )
                        =
                        ( n x. ( f ` <. b , d >. ) )
                      )
                  )
              )
            )
          ->
          {
            b e. NN |
            (
              2 <_ b
              /\
              E. L e. RR
                (
                  m e. NN0 |->
                    sum_ n e. ( 1 ... m )
                      ( 1 / ( f ` <. b , n >. ) )
                )
                ~~>
                L
            )
          }
          =
          { 2 }
        )
      )
  $.
$}
