$(
  Statement-only formalization of PutnamBench corpus artifact
  putnam_2009_b6: every positive integer is the endpoint of a 2010-term
  integer sequence generated by adding a nonnegative power of two to an
  earlier term or taking the remainder of two earlier positive terms. This
  file contains no proof.
$)

$[ lib/set.mm $]

$(
  The class ZZ ^m NN0 is the class of all integer-valued sequences indexed
  by the nonnegative integers. Restricting the recurrence condition to
  1 ... 2009 gives exactly the source's terms after a(0) through a(2009);
  values outside that finite range are unconstrained.

  Quantifying n over NN is equivalent to the source's natural-number
  hypothesis n > 0. The earlier indices and the nonnegative exponent remain
  internally existentially quantified. SetMM's mod operation accepts integer
  operands here, and the explicit positivity hypotheses on both earlier terms
  preserve the source remainder case.

  The final declaration is the single unproved $a corpus statement; this
  database contains no $p proof statement.
$)

