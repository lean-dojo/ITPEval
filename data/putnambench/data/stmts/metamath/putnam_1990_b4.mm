$(
  Statement-only formalization of PutnamBench corpus artifact
  putnam_1990_b4: every finite group irredundantly generated by two elements
  has a cyclic sequence of twice its order in which every group element
  occurs twice and each step right-multiplies by a generator. This file
  contains no proof.
$)

$[ lib/set.mm $]

$(
  In SetMM, G e. Grp supplies an arbitrary group, Base ` G is its carrier,
  +g ` G is its group operation, and the Moore closure in SubGrp ` G is
  subgroup generation. Thus the three closure conditions say that a and b
  generate G together but neither generates G alone.

  The ordinal 0 ..^ ( 2 x. n ) represents Fin (2*n). The witness g is a
  function on exactly this finite cyclic index set. Restricting the source
  witness NN0 --> Base ` G to these indices gives this representation, and
  every such finite function extends to NN0 because a group carrier is
  nonempty, so the existential statements are equivalent. Fiber cardinality
  two expresses that every carrier element occurs exactly twice, and mod
  makes the last step return to index zero. The final declaration is the
  single unproved $a corpus statement; this database contains no $p proof
  statement.
$)

