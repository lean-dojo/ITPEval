(*
  Statement-only formalization of PutnamBench corpus artifact putnam_1990_b4:
  a finite group generated by two elements, but by neither element alone,
  admits a cyclic sequence in which every group element occurs exactly twice
  and each step is right multiplication by one of the generators. This file
  contains no proof.
*)

let statement =
  `let putnam_1990_b4_solution = T in
   let is_group =
     \(mul:G->G->G) (identity:G) (ginv:G->G).
       (!x y z:G. mul (mul x y) z = mul x (mul y z)) /\
       (!x:G. mul identity x = x /\ mul x identity = x) /\
       (!x:G.
          mul (ginv x) x = identity /\ mul x (ginv x) = identity) in
   let is_subgroup =
     \(mul:G->G->G) (identity:G) (ginv:G->G) (H:G->bool).
       identity IN H /\
       (!x:G. x IN H ==> ginv x IN H) /\
       (!x y:G. x IN H /\ y IN H ==> mul x y IN H) in
   let generated_by =
     \(mul:G->G->G) (identity:G) (ginv:G->G) (S:G->bool).
       !H:G->bool.
         is_subgroup mul identity ginv H /\ S SUBSET H
         ==> H = (UNIV:G->bool) in
   ((!mul:G->G->G. !identity:G. !ginv:G->G. !n:num. !a b:G.
       FINITE (UNIV:G->bool) /\
       CARD (UNIV:G->bool) = n /\
       is_group mul identity ginv /\
       generated_by mul identity ginv {a,b} /\
       ~(generated_by mul identity ginv {a}) /\
       ~(generated_by mul identity ginv {b})
       ==>
       ?g:num->G.
         (!x:G. CARD {i:num | i < 2 * n /\ g i = x} = 2) /\
         (!i:num.
            i < 2 * n
            ==> g ((i + 1) MOD (2 * n)) = mul (g i) a \/
                g ((i + 1) MOD (2 * n)) = mul (g i) b))
     <=> putnam_1990_b4_solution)`;;
