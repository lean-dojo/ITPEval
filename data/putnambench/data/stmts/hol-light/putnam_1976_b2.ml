(*
  Statement-only formalization of PutnamBench artifact putnam_1976_b2:
  a group generated by A and B with the stated order and conjugation
  relations has exactly eight square elements, represented by the listed
  words in A and B. This file contains no proof.
*)

let statement =
  `let is_group =
     \(mul:G->G->G) (identity:G) (ginv:G->G).
       (!x y z:G. mul (mul x y) z = mul x (mul y z)) /\
       (!x:G. mul identity x = x /\ mul x identity = x) /\
       (!x:G.
          mul (ginv x) x = identity /\ mul x (ginv x) = identity) in
   let natural_power =
     \(mul:G->G->G) (identity:G) (x:G) (n:num).
       @y:G.
         ?powers:num->G.
           powers 0 = identity /\
           (!k:num. powers (SUC k) = mul x (powers k)) /\
           powers n = y in
   let integer_power =
     \(mul:G->G->G) (identity:G) (ginv:G->G) (x:G) (n:int).
       if (&0:int) <= n
       then natural_power mul identity x (num_of_int n)
       else natural_power mul identity (ginv x) (num_of_int (--n)) in
   let word =
     \(mul:G->G->G) (identity:G) (ginv:G->G) (A:G) (B:G)
       (w:(int#int)list).
       ITLIST
         (\t acc.
            mul
              (mul
                (integer_power mul identity ginv A (FST t))
                (integer_power mul identity ginv B (SND t)))
              acc)
         w identity in
   !mul:G->G->G identity:G ginv:G->G A B:G.
     is_group mul identity ginv /\
     natural_power mul identity A 4 = identity /\
     ~(natural_power mul identity A 2 = identity) /\
     natural_power mul identity B 7 = identity /\
     ~(B = identity) /\
     mul (mul (mul A B) (ginv A)) B = identity /\
     (!g:G.
        ?w:(int#int)list. g = word mul identity ginv A B w)
     ==>
     let squares = {g:G | ?C:G. mul C C = g} in
     CARD squares = 8 /\
     squares =
       IMAGE (word mul identity ginv A B)
         {[((&0:int),(&0:int))],
          [((&2:int),(&0:int))],
          [((&0:int),(&1:int))],
          [((&0:int),(&2:int))],
          [((&0:int),(&3:int))],
          [((&0:int),(&4:int))],
          [((&0:int),(&5:int))],
          [((&0:int),(&6:int))]}`;;
