$(
  Statement-only formalization of Thousand Theorems corpus artifact Q1687147
  (thousand-theorems__metamath__Q1687147), "Sprague-Grundy theorem": every
  well-founded impartial combinatorial game is equivalent to the Nim game
  whose heap ordinal is its Grundy value. This file contains no proof.
$)

$[ lib/set.mm $]

$(
  An IGame is represented by its set V of weak subpositions, its root r, and
  child-to-parent left and right move relations L and R. Q1687147Game requires
  every node to reach r, an ordinal rank decreasing along every move, and
  extensionality of the two option sets. These are exactly the set-sized
  well-founded extensional graphs generated by Lean's IGame constructor; no
  finiteness or countability restriction is imposed.

  Q1687147Positions adjoins a positive and a negative copy of every game
  position and a tagged position for every ordinal in a bounding ordinal H.
  The negative-copy move rules swap left and right moves, exactly encoding
  game negation. The ordinal positions have every smaller ordinal as both a
  left and a right move, exactly encoding nim. Q1687147Order is the defining
  well-founded recursion for the combinatorial-game relation a <= b: no left
  option of a is >= b and no right option of b is <= a.

  Q1687147Impartial says, at every subposition, that the negative copy and
  positive copy are game-equivalent. Since V is precisely the descendant
  closure of r, this is bidirectionally equivalent to Lean's inductive
  Impartial condition, including impartiality of every option. In particular,
  it does not replace the source notion by equality of left and right moves.

  Q1687147Grundy states the exact ordinal mex recursion on right options:
  G(v) is absent among their values and every smaller ordinal occurs. The
  final unproved assertion says that nim(G(r)) and r are mutually <=, which is
  precisely IGame.Impartial.nim_grundy_equiv.
$)

