$(
  Q2631152SetSemiring X C states that C is a semiring of subsets of the
  arbitrary carrier X: it contains the empty set, is closed under
  intersections, and every difference of two members is a finite disjoint
  union of members.

  Q2631152AddContent X C m states that m is an extended-nonnegative-valued
  function on all subsets of X, vanishes at the empty set, and is finitely
  additive whenever a finite disjoint family in C has union in C.
  Q2631152SigmaSubadditive C m is the source's countable subadditivity
  condition for sequences whose terms and union belong to C.

  Q2631152Outer C m A is the induced outer-measure value: the infimum of the
  extended sums of m over all NN0-indexed C-covers of A. Q2631152Measure
  X C m M is the uniquely determined measure on M whose values on measurable
  sets are those outer-measure values. Under
  M = sigaGen ( C union { X } ) this is the carrier-relative SetMM rendering
  of MeasureTheory.AddContent.measure: adjoining X preserves the generated
  sigma-algebra while ensuring that its ambient carrier is all of X.

  The final declaration is the single unproved corpus $a statement. All
  preceding $a declarations are syntax or faithful definitions, and this
  database contains no $p proof statement.
$)

