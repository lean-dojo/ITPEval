$(
  Statement-only formalization of Thousand Theorems corpus artifact Q245098
  (thousand-theorems__metamath__Q245098), "Intermediate value theorem": a
  continuous function from a closed interval in a conditionally complete
  densely ordered space with its order topology to a linearly ordered space
  with closed order relation attains every value between its endpoint values.
  This file contains no proof.
$)

$[ lib/set.mm $]

$(
  Q245098LinearOrder states that R is a reflexive, antisymmetric, transitive,
  total relation on X. Q245098Dense gives an internal point between every
  strictly ordered pair. Q245098CondComplete states that every nonempty subset
  bounded above has a least upper bound and every nonempty subset bounded
  below has a greatest lower bound.

  Q245098OrderClosed states that K is a topology on Y and that S is closed in
  the product topology. The domain topology in the final assertion is the
  SetMM order topology generated by R. Continuity is imposed on the restriction
  of F to the relation-defined closed interval. All auxiliary $a declarations
  are syntax or faithful definitions; the final $a assertion is unproved.
$)

$c Q245098LinearOrder Q245098Dense Q245098CondComplete
   Q245098OrderClosed $.

q245098-linear-order-syntax
  $a wff ( Q245098LinearOrder R X ) $.
q245098-dense-syntax
  $a wff ( Q245098Dense R X ) $.
q245098-cond-complete-syntax
  $a wff ( Q245098CondComplete R X ) $.
q245098-order-closed-syntax
  $a wff ( Q245098OrderClosed S Y K ) $.

${
  $d R X x y z $.

  q245098-linear-order-definition $a |- (
    ( Q245098LinearOrder R X )
    <->
    (
      R C_ ( X X. X )
      /\
      A. x e. X A. y e. X A. z e. X
        (
          x R x
          /\
          (
            ( ( x R y /\ y R x ) -> x = y )
            /\
            (
              ( ( x R y /\ y R z ) -> x R z )
              /\
              ( x R y \/ y R x )
            )
          )
        )
    )
  ) $.
$}

${
