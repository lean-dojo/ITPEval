  q245098-order-closed-definition $a |- (
    ( Q245098OrderClosed S Y K )
    <->
    (
      K e. ( TopOn ` Y )
      /\
      ( ( Y X. Y ) \ S ) e. ( K tX K )
    )
  ) $.
$}

