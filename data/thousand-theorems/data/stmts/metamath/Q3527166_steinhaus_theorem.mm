$(
  Statement-only formalization of Thousand Theorems corpus artifact Q3527166
  (thousand-theorems__metamath__Q3527166), "Steinhaus theorem": in an
  arbitrary locally compact topological group with a Borel inner-regular Haar
  measure, the pointwise quotient E / E of every measurable positive-measure
  set E contains a neighborhood of the group identity. This file contains no
  proof.
$)

$[ lib/set.mm $]

$(
  G ranges over arbitrary SetMM topological groups. SetMM writes the group
  operation, inverse, and identity as +g, -g, and 0g even when the group is
  viewed multiplicatively. Q3527166Quotient therefore renders the source
  pointwise quotient E / E as all x * y^-1 with x,y in E.

  Q3527166Haar expands Mathlib's IsHaarMeasure class: M is a measure on the
  Borel sigma-algebra generated by G's topology, its induced outer measure is
  left-translation invariant, it is finite on compact sets, and it is
  positive on nonempty open sets. Q3527166InnerRegular is exactly Mathlib's
  InnerRegularWRT approximation property for compact subsets of measurable
  sets. Membership of TopOpen G in N-Locally Comp is SetMM's arbitrary-
  neighborhood formulation of local compactness.

  Q3527166Neighborhood says that a set contains an open set containing the
  specified point, equivalently that it belongs to that point's neighborhood
  filter. The final declaration is the single unproved corpus $a statement.
  All preceding $a declarations are syntax or faithful bidirectional
  definitions, and this root file contains no $p proof statement.
$)

