  q1065257-order-top-definition $a |- (
    Q1065257OrderTop R X
  ) = (
    topGen ` ( fi ` (
      { X }
      u.
      (
        ran ( x e. X |-> { y e. X | ( x R y /\ -. y R x ) } )
        u.
        ran ( x e. X |-> { y e. X | ( y R x /\ -. x R y ) } )
      )
    ) )
  ) $.
$}

${
  $d L U V Y $.

  q1065257-filter-definition $a |- (
    ( Q1065257Filter L Y )
    <->
    (
      L C_ ~P Y
      /\
      (
        Y e. L
        /\
        (
          A. U e. L A. V e. L ( U i^i V ) e. L
          /\
          A. U e. L A. V e. ~P Y
            ( U C_ V -> V e. L )
        )
      )
    )
  ) $.
$}

