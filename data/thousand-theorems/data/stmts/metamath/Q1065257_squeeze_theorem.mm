$(
  Q1065257Preorder says that R is a reflexive, transitive relation on X.
  Q1065257OrderTop is the topology generated by the strict upper and lower
  rays x R y and not y R x of that preorder.

  Q1065257Filter uses the axioms of Lean's Filter: it contains the whole
  carrier and is closed under supersets and binary intersections. In
  particular it permits the improper filter containing the empty set, unlike
  SetMM's proper-filter class Fil. Q1065257Tendsto says that every open
  neighborhood of the proposed limit has an eventual inverse image.

  The final declaration is the single unproved corpus $a statement. All
  preceding $a declarations are syntax or faithful definitions, and this
  database contains no $p proof statement.
$)

$c Q1065257Preorder Q1065257OrderTop Q1065257Filter
   Q1065257Tendsto $.

q1065257-preorder-syntax
