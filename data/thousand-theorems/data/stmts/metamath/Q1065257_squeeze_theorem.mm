  q1065257-preorder-definition $a |- (
    ( Q1065257Preorder R X )
    <->
    (
      R C_ ( X X. X )
      /\
      (
        A. x e. X x R x
        /\
        A. x e. X A. y e. X A. z e. X
          ( ( x R y /\ y R z ) -> x R z )
      )
    )
  ) $.
