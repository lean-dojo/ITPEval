$(
  V ranges over SetMM normed vector spaces over RRfld. The hypotheses
  V e. CMetSp and ( TopOpen ` V ) e. 2ndc express completeness and second
  countability for the norm topology, while M is a measure on the Borel
  sigma-algebra generated by that topology.

  Q5445112ContinuousLinear says that L is a bounded real-linear functional.
  Q5445112Map is its pushforward measure. Q5445112GaussianReal characterizes
  the real Gaussian probability measure with mean m and variance v by its
  characteristic function. Thus Q5445112IsGaussian is equivalent to the
  source IsGaussian predicate: every continuous real-linear functional has
  a Gaussian pushforward. The mean and variance witnesses remain internal.

  Q5445112ExpSq is the real-valued function x |-> exp(C * norm(x)^2).
  Q5445112Integrable is membership in the domain of SetMM's real Bochner
  integral. The final $a declaration is the single unproved corpus statement;
  all preceding $a declarations are syntax or explicit bidirectional
  definitions, and this database contains no $p proof statement.
$)

