$(
  S is a sequence of sigma-algebras, one for each natural-numbered state
  space. Q25378690Prefix and Q25378690Path are SetMM dependent function
  spaces. Their sigma-algebras are generated by all measurable coordinate
  cylinders, so no common carrier or finite-table encoding is imposed.

  Q25378690Markov S T K says that K maps every point of the source measurable
  space S to a probability measure on T and that evaluation on every
  T-measurable set is S-measurable. Q25378690LIntegral is the lower Lebesgue
  integral, explicitly defined through extended-nonnegative simple functions.

  Q25378690FiniteLaws S K a x F states the finite-prefix recursion. Through
  cutoff a, F is the Dirac law at the corresponding restriction of the input
  history x. Each later law is obtained by integrating the next kernel K(b)
  against F(b). The final assertion internally quantifies a trajectory kernel
  and requires all its finite-prefix marginals to equal these recursive laws.

  The final declaration is the single unproved corpus $a statement. All
  preceding $a declarations are syntax or faithful definitions, and this
  database contains no $p proof statement.
$)

