$(
  Q468391MetricTopology D is the topology generated by the open balls of the
  real-valued pseudometric D. Q468391Bounded D S says that all pairwise
  distances in S have a common real upper bound, which is equivalent to
  boundedness in the pseudometric bornology.

  Q468391Proper X D states that every closed ball with center in X and real
  radius is compact in the induced subspace topology, exactly expressing the
  proper-space assumption. Q468391SubseqConverges D x p a says that p is a
  strictly increasing map from the natural numbers to themselves and that the
  subsequence n |-> x(p(n)) converges to a in the induced topology.

  Frequent membership along the natural-number atTop filter is rendered in the
  first final assertion by: after every natural index N there is an n >= N
  whose sequence value lies in S. The second final assertion instead requires
  every sequence value to lie in S. Both conclusions retain the internal
  existential limit point in the closure and the internal existential
  subsequence map.

  The two final declarations are the unproved corpus $a statements
  corresponding to the two indexed Lean declarations. All preceding $a
  declarations are syntax or faithful definitions, and this database contains
  no $p proof statement.
$)

