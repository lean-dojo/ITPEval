$(
  Statement-only formalization of Thousand Theorems corpus artifact Q468391
  (thousand-theorems__metamath__Q468391), "Bolzano--Weierstrass theorem":
  in a proper pseudometric space, a sequence frequently contained in a bounded
  set has a strictly increasing subsequence converging to a point in the
  closure of that set; the same conclusion holds when every term lies in the
  set. This file contains no proof.
$)

