$(
  SetMM's PID is the class IDomn intersect LPIR, so it expresses precisely
  the commutative integral-domain and principal-ideal hypotheses on R.
  Q7888360FiniteModule M says that a finite subset of Base ` M spans M; this
  is bidirectionally equivalent to mathlib's Module.Finite R M.

  Q7888360Cyclic R a k is the quotient of the regular left R-module by the
  principal ideal generated by a^k. The group-multiple operation on mulGrp
  is ring exponentiation for k in NN0.

  Q7888360Target R n I p e is the two-factor module product of the free
  module on 0 ..^ n and the direct sum, indexed by the arbitrary finite set
  I, of R/(p(i)^e(i)). SetMM represents this binary product as a dependent
  product over { empty, 1 }; it is canonically linearly equivalent in both
  directions to Lean's module product. Thus nonemptiness of LMIso in the
  final assertion is equivalent to the source Nonempty linear equivalence.

  The final declaration is the single unproved $a corpus statement. All
  preceding root-file $a declarations are syntax or faithful definitions.
  This root statement file contains no $p declaration; imported lib/set.mm
  supplies the independently verified standard-library proofs.
$)

