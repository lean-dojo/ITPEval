$(
  Q253214MetricTopology D is the topology generated by the open balls of the
  pseudometric D. Q253214Bounded D S says that all pairwise distances in S
  have a common real upper bound, the pseudometric characterization of the
  source bornological boundedness predicate.

  Q253214Proper X D says that every closed ball with center in X and arbitrary
  real radius is compact in the induced subspace topology. This is exactly the
  proper-space hypothesis used by the Lean theorem. The final assertion ranges
  over an arbitrary carrier X, real-valued pseudometric D, and subset S of X;
  Haus is SetMM's Hausdorff-space class, Clsd its closed-set operator, and Comp
  its compact-space class.

  The final declaration is the single unproved corpus $a statement. All
  preceding $a declarations are syntax or faithful definitions. There are no
  $p declarations in this root statement file; the included SetMM library is
  a separately verified dependency.
$)

