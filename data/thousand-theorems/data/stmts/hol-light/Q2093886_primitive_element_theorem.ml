(*
  Statement-only formalization of Thousand Theorems corpus artifact Q2093886,
  "Primitive element theorem": every finite-dimensional separable field
  extension is generated by one element. This file contains no proof.
*)

let Q2093886_PRIMITIVE_ELEMENT_THEOREM =
  `let is_field_F =
     \(zeroF0:F) (unitF0:F) (addF0:F->F->F) (mulF0:F->F->F)
      (negF0:F->F) (invF0:F->F).
       ~(zeroF0 = unitF0) /\
       (!x:F. addF0 zeroF0 x = x) /\
       (!x:F. addF0 (negF0 x) x = zeroF0) /\
       (!x y:F. addF0 x y = addF0 y x) /\
       (!x y z:F. addF0 x (addF0 y z) = addF0 (addF0 x y) z) /\
       (!x:F. mulF0 unitF0 x = x) /\
       (!x y:F. mulF0 x y = mulF0 y x) /\
       (!x y z:F. mulF0 x (mulF0 y z) = mulF0 (mulF0 x y) z) /\
       (!x y z:F.
          mulF0 x (addF0 y z) =
          addF0 (mulF0 x y) (mulF0 x z)) /\
       invF0 zeroF0 = zeroF0 /\
       (!x:F. ~(x = zeroF0) ==> mulF0 (invF0 x) x = unitF0) in
   let is_field_E =
     \(zeroE0:E) (unitE0:E) (addE0:E->E->E) (mulE0:E->E->E)
      (negE0:E->E) (invE0:E->E).
       ~(zeroE0 = unitE0) /\
       (!x:E. addE0 zeroE0 x = x) /\
       (!x:E. addE0 (negE0 x) x = zeroE0) /\
       (!x y:E. addE0 x y = addE0 y x) /\
       (!x y z:E. addE0 x (addE0 y z) = addE0 (addE0 x y) z) /\
       (!x:E. mulE0 unitE0 x = x) /\
       (!x y:E. mulE0 x y = mulE0 y x) /\
       (!x y z:E. mulE0 x (mulE0 y z) = mulE0 (mulE0 x y) z) /\
       (!x y z:E.
          mulE0 x (addE0 y z) =
          addE0 (mulE0 x y) (mulE0 x z)) /\
       invE0 zeroE0 = zeroE0 /\
       (!x:E. ~(x = zeroE0) ==> mulE0 (invE0 x) x = unitE0) in
   let is_field_embedding =
     \(zeroF:F) (oneF:F) (addF:F->F->F) (mulF:F->F->F)
      (zeroE:E) (oneE:E) (addE:E->E->E) (mulE:E->E->E)
      (embedding:F->E).
       embedding zeroF = zeroE /\
       embedding oneF = oneE /\
       (!x y:F.
          embedding (addF x y) = addE (embedding x) (embedding y)) /\
       (!x y:F.
          embedding (mulF x y) = mulE (embedding x) (embedding y)) /\
       (!x y:F. embedding x = embedding y ==> x = y) in
   let field_power =
     \(unitE:E) (mul:E->E->E) (x:E) (n:num).
       ITLIST mul (REPLICATE n x) unitE in
   let is_polynomial =
     \(zeroF:F) (p:num->F). FINITE {n | ~(p n = zeroF)} in
   let polynomial_zero =
     \(zeroF:F). \n:num. zeroF in
   let polynomial_one =
     \(zeroF:F) (oneF:F). \n:num. if n = 0 then oneF else zeroF in
   let polynomial_add =
     \(addF:F->F->F) (p:num->F) (q:num->F).
       \n:num. addF (p n) (q n) in
   let polynomial_mul =
     \(addF:F->F->F) (mulF:F->F->F) (p:num->F) (q:num->F).
       \n:num.
         iterate addF (0..n) (\i:num. mulF (p i) (q (n - i))) in
   let natural_multiple =
     \(zeroF:F) (addF:F->F->F) (n:num) (x:F).
       ITLIST addF (REPLICATE n x) zeroF in
   let polynomial_derivative =
     \(zeroF:F) (addF:F->F->F) (p:num->F).
       \n:num. natural_multiple zeroF addF (n + 1) (p (n + 1)) in
   let polynomial_eval =
     \(zeroF:F) (oneE:E) (addE:E->E->E) (mulE:E->E->E)
      (embedding:F->E) (p:num->F) (x:E).
       iterate addE {n | ~(p n = zeroF)}
         (\n:num. mulE (embedding (p n)) (field_power oneE mulE x n)) in
   let is_separable_polynomial =
     \(zeroF:F) (oneF:F) (addF:F->F->F) (mulF:F->F->F)
      (p:num->F).
       is_polynomial zeroF p /\
       ~(p = polynomial_zero zeroF) /\
       ?a b:num->F.
         is_polynomial zeroF a /\
         is_polynomial zeroF b /\
         polynomial_add addF
           (polynomial_mul addF mulF a p)
           (polynomial_mul addF mulF b
             (polynomial_derivative zeroF addF p)) =
         polynomial_one zeroF oneF in
   let is_separable_extension =
     \(zeroF:F) (oneF:F) (addF:F->F->F) (mulF:F->F->F)
      (oneE:E) (addE:E->E->E) (mulE:E->E->E)
      (embedding:F->E).
       !x:E.
         ?p:num->F.
           is_separable_polynomial zeroF oneF addF mulF p /\
           polynomial_eval zeroF oneE addE mulE embedding p x =
           embedding zeroF in
   let finite_linear_combination =
     \(zeroE:E) (addE:E->E->E) (mulE:E->E->E)
      (embedding:F->E) (n:num) (basis:num->E)
      (coeff:num->F) (x:E).
       ?partial:num->E.
         partial 0 = zeroE /\
         (!i:num.
            i < n
            ==> partial (SUC i) =
                addE (partial i) (mulE (embedding (coeff i)) (basis i))) /\
         partial n = x in
   let is_finite_dimensional =
     \(zeroE:E) (addE:E->E->E) (mulE:E->E->E) (embedding:F->E).
       ?n:num. ?basis:num->E.
         !x:E. ?coeff:num->F.
           finite_linear_combination
             zeroE addE mulE embedding n basis coeff x in
   let is_subfield =
     \(zeroE:E) (oneE:E) (addE:E->E->E) (mulE:E->E->E)
      (negE:E->E) (invE:E->E) (subfield:E->bool).
       subfield zeroE /\
       subfield oneE /\
       (!x:E.
          subfield x
          ==> subfield (negE x) /\ subfield (invE x)) /\
       (!x y:E.
          subfield x /\ subfield y
          ==> subfield (addE x y) /\ subfield (mulE x y)) in
   !zeroF oneF:F. !addF mulF:F->F->F. !negF invF:F->F.
   !zeroE oneE:E. !addE mulE:E->E->E. !negE invE:E->E.
   !embedding:F->E.
     is_field_F zeroF oneF addF mulF negF invF /\
     is_field_E zeroE oneE addE mulE negE invE /\
     is_field_embedding
       zeroF oneF addF mulF zeroE oneE addE mulE embedding /\
     is_finite_dimensional zeroE addE mulE embedding /\
     is_separable_extension
       zeroF oneF addF mulF oneE addE mulE embedding
     ==> ?alpha:E.
           !subfield:E->bool.
             is_subfield zeroE oneE addE mulE negE invE subfield /\
             (!a:F. subfield (embedding a)) /\
             subfield alpha
             ==> !x:E. subfield x`;;
