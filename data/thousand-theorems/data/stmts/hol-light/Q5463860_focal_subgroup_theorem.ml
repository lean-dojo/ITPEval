let Q5463860_FOCAL_SUBGROUP_THEOREM =
  `let commutator_element =
     \(G:A group) (x:A) (u:A).
       group_mul G
         (group_mul G (group_mul G x u) (group_inv G x))
         (group_inv G u) in
   let is_p_group =
     \(G:A group) (p:num).
       !x:A.
         x IN group_carrier G
         ==> ?k:num. group_pow G x (p EXP k) = group_id G in
   let is_sylow =
     \(G:A group) (p:num) (P:A->bool).
       P subgroup_of G /\
       is_p_group (subgroup_generated G P) p /\
       (!Q:A->bool.
          Q subgroup_of G /\
          is_p_group (subgroup_generated G Q) p /\
          P SUBSET Q
          ==> Q = P) in
   let has_finite_index =
     \(G:A group) (P:A->bool).
       FINITE {right_coset G P x | x | x IN group_carrier G} in
   let commutator_subgroup =
     \(G:A group).
       group_carrier
         (subgroup_generated G
           {g:A |
              ?x u:A.
                x IN group_carrier G /\
                u IN group_carrier G /\
                commutator_element G x u = g}) in
   let focal_subgroup =
     \(G:A group) (P:A->bool).
       group_carrier
         (subgroup_generated G
           {g:A |
              g IN P /\
              ?x:A.
                x IN P /\
                ?u:A.
                  u IN group_carrier G /\
                  g = commutator_element G x u}) in
   !(G:A group) (p:num) (P:A->bool).
     prime p /\
     is_sylow G p P /\
     has_finite_index G P
     ==> commutator_subgroup G INTER P = focal_subgroup G P`;;
