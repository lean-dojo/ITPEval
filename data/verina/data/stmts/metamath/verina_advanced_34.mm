${
  $d i A B C $.

  verina34-push-graph-definition $a |- (
    VERINA34PushGraph A B C
  ) <-> (
    (
      (
        A e. Word ZZ
        /\
        B e. ZZ
      )
      /\
      C e. Word ZZ
    )
    /\
    (
      ( # ` C ) = ( ( # ` A ) + 1 )
      /\
      (
        A. i e. ( 0 ..^ ( # ` A ) )
          ( C ` i ) = ( A ` i )
        /\
        ( C ` ( # ` A ) ) = B
      )
    )
  ) $.
$}

