$(
  Statement-only formalization of the VERINA corpus artifact
  verina_advanced_34 (verina__metamath__verina_advanced_34), catalog title
  longestIncreasingSubsequence: the exact lower-bound binary-search and
  tail-replacement array program computes the integer length of a longest
  strictly increasing subsequence of an arbitrary finite integer list.
  This file contains no proof.
$)

$[ lib/set.mm $]

$(
  SetMM's ZZ and NN0 are the full integer and natural-number domains, and
  Word ZZ is exactly the type of arbitrary finite integer lists and arrays.
  For a word w, # ` w is its natural-number length, w ` k is zero-based
  lookup, and 0 ..^ ( # ` w ) is its complete index set.

  VERINA34ArrayGetBang reproduces Lean Array.get! on integer arrays, including
  its default value zero outside the array. VERINA34BinarySearchLeftGraph is
  the complete finite execution trace of binarySearchLeft for arbitrary array,
  number, and natural left and right arguments. At each nonterminal state it
  uses floor((left + right) / 2); the equality and greater-than source branches
  have the same recursive bounds and are combined without changing the
  computation. VERINA34BinarySearchLeft selects the unique trace result.

  VERINA34Push and VERINA34SetBang reproduce Array.push and Array.set!,
  including the unchanged-array behavior of set! at an out-of-range index.
  VERINA34LoopGraph starts with the source head! singleton after the explicit
  empty-input branch and records every mutable sub array while traversing
  nums.tail. Each step performs exactly the source last-element comparison,
  push, binary-search, or replacement. VERINA34LongestIncreasingSubsequence
  selects the resulting array length, canonically embedded in ZZ just as
  Int.ofNat does.

  VERINA34Subsequence uses an internally existential increasing word of input
  indices, so it describes exactly the words generated by the postcondition's
  fold from [[]] and subsequent List.reverse. VERINA34StrictlyIncreasing is
  exactly List.Pairwise (<). Consequently VERINA34Post is bidirectionally
  equivalent to filtering that generated list, mapping List.length, requiring
  contains result, and requiring all lengths to be at most result: its
  existential conjunct is contains, and its universal conjunct is all.

  VERINA34Pre is the source True precondition together with the List Int input
  type. The proof-valued precondition argument is computationally and
  propositionally unused and is omitted from the target function and
  predicate. The final $a declaration is the source correctness proposition.
  Every earlier $a is syntax or a faithful definition, and this database has
  no $p declaration.
$)

