${
  $d k t A B $.

  verina34-loop-graph-definition $a |- (
    VERINA34LoopGraph A B
  ) <-> (
    (
      A e. Word ZZ
      /\
      B e. NN0
    )
    /\
    (
      (
        ( # ` A ) = 0
        /\
        B = 0
      )
      \/
      (
        0 < ( # ` A )
        /\
        E. t e. Word ( Word ZZ )
          (
            (
              (
                ( # ` t ) = ( # ` A )
                /\
                ( # ` ( t ` 0 ) ) = 1
              )
              /\
              ( ( t ` 0 ) ` 0 ) = ( A ` 0 )
            )
            /\
            (
              A. k e. ( 1 ..^ ( # ` A ) )
                (
                  t ` k
                ) = if (
                  (
                    ( t ` ( k - 1 ) )
                    ` ( ( # ` ( t ` ( k - 1 ) ) ) - 1 )
                  ) < ( A ` k ) ,
                  (
                    VERINA34Push
                      ( t ` ( k - 1 ) )
                      ( A ` k )
                  ) ,
                  (
                    VERINA34SetBang
                      ( t ` ( k - 1 ) )
                      (
                        VERINA34BinarySearchLeft
                          ( t ` ( k - 1 ) )
                          ( A ` k )
                          0
                          (
                            ( # ` ( t ` ( k - 1 ) ) ) - 1
                          )
                      )
                      ( A ` k )
                  )
                )
              /\
              B = (
                # ` ( t ` ( ( # ` A ) - 1 ) )
              )
            )
          )
      )
    )
  ) $.
$}

