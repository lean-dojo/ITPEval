verina34-array-get-bang-definition $a |- (
  VERINA34ArrayGetBang A B
) = if (
  B < ( # ` A ) ,
  ( A ` B ) ,
  0
) $.

${
  $d i l r y A B C D E $.

  verina34-binary-search-left-graph-definition $a |- (
    VERINA34BinarySearchLeftGraph A B C D E
  ) <-> (
    (
      (
        (
          A e. Word ZZ
          /\
          B e. ZZ
        )
        /\
        (
          C e. NN0
          /\
          D e. NN0
        )
      )
      /\
      E e. NN0
    )
    /\
    E. l e. Word NN0
      E. r e. Word NN0
        (
          (
            (
              (
                ( # ` l ) = ( # ` r )
                /\
                0 < ( # ` l )
              )
              /\
              (
                ( l ` 0 ) = C
                /\
                ( r ` 0 ) = D
              )
            )
            /\
            (
              (
                r ` ( ( # ` r ) - 1 )
              ) <_ (
                l ` ( ( # ` l ) - 1 )
              )
              /\
              E = ( l ` ( ( # ` l ) - 1 ) )
            )
          )
          /\
          A. i e. ( 0 ..^ ( ( # ` l ) - 1 ) )
            (
              ( l ` i ) < ( r ` i )
              /\
              (
                (
                  l ` ( i + 1 )
                ) = if (
                  (
                    VERINA34ArrayGetBang
                      A
                      (
                        |_ ` (
                          (
                            ( l ` i ) + ( r ` i )
                          ) / 2
                        )
                      )
                  ) < B ,
                  (
                    (
                      |_ ` (
                        (
                          ( l ` i ) + ( r ` i )
                        ) / 2
                      )
                    ) + 1
                  ) ,
                  ( l ` i )
                )
                /\
                (
                  r ` ( i + 1 )
                ) = if (
                  (
                    VERINA34ArrayGetBang
                      A
                      (
                        |_ ` (
                          (
                            ( l ` i ) + ( r ` i )
                          ) / 2
                        )
                      )
                  ) < B ,
                  ( r ` i ) ,
                  (
                    |_ ` (
                      (
                        ( l ` i ) + ( r ` i )
                      ) / 2
                    )
                  )
                )
              )
            )
        )
  ) $.
$}

