${
  $d i j p A B $.

  verina34-subsequence-definition $a |- (
    VERINA34Subsequence A B
  ) <-> (
    (
      A e. Word ZZ
      /\
      B e. Word ZZ
    )
    /\
    E. p e. Word NN0
      (
        (
          ( # ` p ) = ( # ` B )
          /\
          A. i e. ( 0 ..^ ( # ` p ) )
            (
              ( p ` i ) < ( # ` A )
              /\
              ( B ` i ) = ( A ` ( p ` i ) )
            )
        )
        /\
        A. i e. ( 0 ..^ ( # ` p ) )
          A. j e. ( 0 ..^ ( # ` p ) )
            (
              i < j
              ->
              ( p ` i ) < ( p ` j )
            )
      )
  ) $.
$}

${
  $d i j A $.

  verina34-strictly-increasing-definition $a |- (
    VERINA34StrictlyIncreasing A
  ) <-> (
    (
      A e. Word ZZ
      /\
      A. i e. ( 0 ..^ ( # ` A ) )
        A. j e. ( 0 ..^ ( # ` A ) )
          (
            i < j
            ->
            ( A ` i ) < ( A ` j )
          )
    )
  ) $.
$}

${
  $d s A B $.

  verina34-postcondition-definition $a |- (
    VERINA34Post A B
  ) <-> (
    (
      A e. Word ZZ
      /\
      B e. NN0
    )
    /\
    (
      E. s e. Word ZZ
        (
          (
            VERINA34Subsequence A s
            /\
            VERINA34StrictlyIncreasing s
          )
          /\
          ( # ` s ) = B
        )
      /\
      A. s e. Word ZZ
        (
          (
            VERINA34Subsequence A s
            /\
            VERINA34StrictlyIncreasing s
          )
          ->
          ( # ` s ) <_ B
        )
    )
  ) $.
$}

verina-advanced-34-longest-increasing-subsequence
  $a |- A. w e. Word ZZ
    (
      ( VERINA34Pre w )
      ->
      (
        VERINA34Post
          w
          ( VERINA34LongestIncreasingSubsequence w )
      )
    )
  $.
