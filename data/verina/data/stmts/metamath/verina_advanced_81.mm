${
  $d R A B C a b t u $.

  verina81-insert-graph-definition $a |- (
    VERINA81InsertGraph A B C
  ) <-> (
    (
      (
        A e. ZZ
        /\
        B e. Word ZZ
      )
      /\
      C e. Word ZZ
    )
    /\
    A. R
      (
        (
          (
            A. a e. ZZ
              <. <. a , (/) >. , <" a "> >. e. R
            /\
            A. a e. ZZ
              A. b e. ZZ
                A. t e. Word ZZ
                  (
                    a <_ b
                    ->
                    <.
                      <. a , ( <" b "> ++ t ) >.
                      ,
                      ( <" a "> ++ ( <" b "> ++ t ) )
                    >. e. R
                  )
          )
          /\
          A. a e. ZZ
            A. b e. ZZ
              A. t e. Word ZZ
                A. u e. Word ZZ
                  (
                    (
                      ( -. a <_ b )
                      /\
                      <. <. a , t >. , u >. e. R
                    )
                    ->
                    <.
                      <. a , ( <" b "> ++ t ) >.
                      ,
                      ( <" b "> ++ u )
                    >. e. R
                  )
        )
        ->
        <. <. A , B >. , C >. e. R
      )
  ) $.
$}

${
  $d y A B $.

  verina81-insert-definition $a |- (
    VERINA81Insert A B
  ) = (
    iota_ y e. Word ZZ
      ( VERINA81InsertGraph A B y )
  ) $.
$}

${
