${
  $d R A B C D h t s a y $.

  verina81-aux-graph-definition $a |- (
    VERINA81AuxGraph A B C D
  ) <-> (
    (
      (
        A e. Word ZZ
        /\
        B e. Word ZZ
      )
      /\
      (
        C e. Word ZZ
        /\
        D e. Word ZZ
      )
    )
    /\
    A. R
      (
        (
          (
            A. s e. Word ZZ
              A. a e. Word ZZ
                <.
                  <. <. (/) , s >. , a >.
                  ,
                  ( reverse ` a )
                >. e. R
            /\
            A. h e. ZZ
              A. t e. Word ZZ
                A. s e. Word ZZ
                  A. a e. Word ZZ
                    A. y e. Word ZZ
                      (
                        (
                          h e. ran s
                          /\
                          <. <. <. t , s >. , a >. , y >. e. R
                        )
                        ->
                        <.
                          <. <. ( <" h "> ++ t ) , s >. , a >.
                          ,
                          y
                        >. e. R
                      )
          )
          /\
          A. h e. ZZ
            A. t e. Word ZZ
              A. s e. Word ZZ
                A. a e. Word ZZ
                  A. y e. Word ZZ
                    (
                      (
                        h e/ ran s
                        /\
                        <.
                          <.
                            <. t , ( <" h "> ++ s ) >.
                            ,
                            ( <" h "> ++ a )
                          >.
                          ,
                          y
                        >. e. R
                      )
                      ->
                      <.
                        <. <. ( <" h "> ++ t ) , s >. , a >.
                        ,
                        y
                      >. e. R
                    )
        )
        ->
        <. <. <. A , B >. , C >. , D >. e. R
      )
  ) $.
$}

