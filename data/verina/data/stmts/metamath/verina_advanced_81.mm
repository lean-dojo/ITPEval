$(
  Statement-only formalization of the VERINA corpus artifact
  verina_advanced_81 (verina__metamath__verina_advanced_81), catalog title
  uniqueSorted: exact duplicate removal followed by insertion sorting on
  arbitrary finite integer lists, with permutation and pairwise-order
  correctness. This file contains no proof.
$)

$[ lib/set.mm $]

$(
  SetMM's ZZ is the full integer domain, with its native equality and order,
  and Word ZZ is exactly the type of arbitrary finite integer lists. The
  empty word (/), singleton word <" x ">, concatenation ++, range, and
  reverse are therefore the corresponding grounded list operations.

  VERINA81InsertGraph is the least relation closed under the three exact
  source equations for insert: the empty case, the x <= head case, and the
  recursive else case. VERINA81InsertionSortGraph is likewise the least
  relation generated by the empty case and the recursive tail-sort followed
  by that exact insert. The iota definitions select their unique outputs,
  so these are deterministic functions rather than unconstrained relations.

  VERINA81AuxGraph is the least relation closed under the exact removeDups
  auxiliary equations. Membership in the Lean seen list is membership in
  the range of its SetMM word; a new head is prepended to both seen and the
  accumulator; and the empty case reverses the accumulator. RemoveDups calls
  this helper with two empty words. On integer lists, Lean List.eraseDups has
  exactly this first-occurrence-preserving computation, so VERINA81EraseDups
  is definitionally identified with VERINA81RemoveDups. VERINA81UniqueSorted
  is precisely insertionSort (removeDups arr).

  VERINA81Perm is List.isPerm, expressed by equality of every integer's
  finite multiplicity. VERINA81PairwiseLE is List.Pairwise (fun x y => x <=
  y), expressed over every earlier/later pair of zero-based indices.
  VERINA81Pre is the source True precondition on the typed input domain, and
  VERINA81Post is the exact source conjunction for the executable result.
  The final declaration is the source correctness proposition. Every $a
  declaration is syntax or a faithful definition, and there is no proof
  declaration in this database.
$)

$c
  VERINA81InsertGraph VERINA81Insert
  VERINA81InsertionSortGraph VERINA81InsertionSort
  VERINA81AuxGraph VERINA81Aux
  VERINA81RemoveDups VERINA81EraseDups VERINA81UniqueSorted
  VERINA81Perm VERINA81PairwiseLE VERINA81Pre VERINA81Post
$.

verina81-insert-graph-syntax
  $a wff ( VERINA81InsertGraph A B C ) $.
verina81-insert-syntax
  $a class ( VERINA81Insert A B ) $.
verina81-insertion-sort-graph-syntax
  $a wff ( VERINA81InsertionSortGraph A B ) $.
verina81-insertion-sort-syntax
