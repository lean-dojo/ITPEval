  ) <-> (
    (
      A e. Word ZZ
      /\
      B e. Word ZZ
    )
    /\
    A. R
      (
        (
          <. (/) , (/) >. e. R
          /\
          A. h e. ZZ
            A. t e. Word ZZ
              A. u e. Word ZZ
                (
                  <. t , u >. e. R
                  ->
                  <.
                    ( <" h "> ++ t )
                    ,
                    ( VERINA81Insert h u )
                  >. e. R
                )
        )
        ->
        <. A , B >. e. R
      )
  ) $.
$}

