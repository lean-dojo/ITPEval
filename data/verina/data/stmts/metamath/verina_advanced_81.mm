) $.

${
  $d i j x A B $.

  verina81-permutation-definition $a |- (
    VERINA81Perm A B
  ) <-> (
    (
      A e. Word ZZ
      /\
      B e. Word ZZ
    )
    /\
    A. x e. ZZ
      (
        # ` {
          i e. ( 0 ..^ ( # ` A ) )
          |
          ( A ` i ) = x
        }
      ) = (
        # ` {
          j e. ( 0 ..^ ( # ` B ) )
          |
          ( B ` j ) = x
        }
      )
  ) $.
$}

${
  $d i j A $.

  verina81-pairwise-le-definition $a |- (
    VERINA81PairwiseLE A
  ) <-> (
    A e. Word ZZ
    /\
    A. i e. ( 0 ..^ ( # ` A ) )
      A. j e. ( 0 ..^ ( # ` A ) )
        (
          i < j
          ->
          ( A ` i ) <_ ( A ` j )
        )
  ) $.
$}

verina81-precondition-definition $a |- (
  VERINA81Pre A
) <-> (
  A e. Word ZZ
) $.

verina81-postcondition-definition $a |- (
  VERINA81Post A B
) <-> (
  (
    A e. Word ZZ
    /\
    B e. Word ZZ
  )
  /\
  (
    (
      VERINA81Perm
        ( VERINA81EraseDups A )
        B
    )
    /\
    ( VERINA81PairwiseLE B )
  )
) $.

verina-advanced-81-unique-sorted $a |- A. w e. Word ZZ
  (
    ( VERINA81Pre w )
    ->
    (
      VERINA81Post
        w
        ( VERINA81UniqueSorted w )
    )
  )
$.
